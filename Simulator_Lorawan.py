import numpy as np

class EnergyModel:
    def __init__(self, tx_power, rx_power, idle_power, standby_power, n_devices, network_throughput, voltage=3.3):
        """
        Modelo de consumo de energia de um dispositivo LoRaWAN baseado na equação matemática fornecida.

        Parâmetros:
        - tx_power: Corrente ao transmitir (mA)
        - rx_power: Corrente ao receber (mA)
        - idle_power: Corrente em estado inativo (mA)
        - standby_power: Corrente no estado de espera (mA)
        - num_devices: Número total de dispositivos na rede
        - network_throughput: Objeto da classe NetworkThroughput para obter o ToA médio, p(s) e N_c
        - voltage: Tensão da bateria (V) (Padrão: 3.3V)
        """
        self.tx_power = tx_power  # Corrente de transmissão (mA)
        self.rx_power = rx_power  # Corrente de recepção (mA)
        self.idle_power = idle_power  # Corrente em estado inativo (mA)
        self.standby_power = standby_power  # Corrente no estado de espera (mA)
        self.num_devices =num_devices  # Número de dispositivos na rede
        self.voltage = voltage  # Tensão da bateria (V)
        self.energy_consumed = 0  # Energia total consumida (mWh)
        self.network_throughput = network_throughput  # Objeto que calcula o ToA, p(s) e N_c

    def update_energy(self, mode, duration, device, rd1, rd2, trx1, trx2, receive_delay1, receive_delay2):
        """
        Atualiza o consumo de energia do dispositivo usando o modelo matemático fornecido.

        Parâmetros:
        - mode: Modo de operação ('transmit', 'receive', 'idle')
        - duration: Tempo total do ciclo de transmissão (segundos)
        - device: O dispositivo que está consumindo energia
        - rd1, rd2: Tempo de dormência antes e depois da recepção (segundos)
        - trx1, trx2: Tempo de recepção 1 e 2 (segundos)
        - receive_delay1, receive_delay2: Delays da recepção (segundos)
        """
        if duration <= 0:
            print(f"🔋⚠️ [LOG] Duração inválida para atualização de energia: {duration}s. Ignorando...")
            return


        n_covered = self.network_throughput.calculate_covered_devices()


        if n_covered == 0:
            print(f"⚠️ [LOG ENERGY] Nenhum dispositivo coberto. Energia não será atualizada para Device {device.device_id}.")
            return


        toa_dict = self.network_throughput.calculate_avg_airtime()
        toa = toa_dict.get(device.sf, 0)
        #print(f"air time :{toa}")

        sf_proportions = self.network_throughput.calculate_sf_proportions()
        p_s = sf_proportions.get(device.sf, 0)
        #print(f"[LOG ENERGY]proporção;{p_s}")


        e_active = (1/2) * p_s * n_covered * self.voltage * (
            (toa * self.tx_power) + (rd1 * self.standby_power) + (trx1 * self.rx_power)
        ) + (1/2) * p_s * n_covered * self.voltage * (
            (toa * self.tx_power) + ((rd2 - trx1) * self.standby_power) + ((trx1 + trx2) * self.rx_power)
        )


        e_idle = (1/2) * p_s * n_covered * self.voltage * (
            (duration - (toa + trx1 + receive_delay1)) * self.idle_power
        ) + (1/2) * p_s * n_covered * self.voltage * (
            (duration - (toa + receive_delay2 + trx2)) * self.idle_power
        )


        energy_total = e_active + e_idle
        self.energy_consumed += energy_total


        print(f"🔋 [LOG ENEGY] ToA: {toa:.2f}s | p(s): {p_s:.4f} | N_c: {n_covered} | "
              f"Modo: {mode.upper()} | Tempo: {duration:.2f}s | Consumo: {self.energy_consumed:.2f} mWh")

    def log_energy(self):
        """Exibe o consumo total de energia do dispositivo."""
        print(f"🔋 [LOG ENERGY] Consumo total de energia: {self.energy_consumed:.2} mWh")

    def reset_energy(self):
        """Reseta o consumo de energia para zero."""
        self.energy_consumed = 0
        print("🔋 [LOG] Consumo de energia resetado.")

