class Network:
    def __init__(self, num_devices, num_gateways, area_size, lambda_rate, speed, sf_range, tx_power, frequency_mhz, ht_m, hr_m, bw, cr, pl, simulation_time, adr_enabled, pathloss):

        self.frequency_mhz = frequency_mhz  # Frequências disponíveis (MHz)
        self.ht_m = ht_m  # Altura dos dispositivos (m)
        self.hr_m = hr_m  # Altura dos gateways (m)
        self.bw = bw  # Largura de banda (Hz)
        self.cr = cr  # Taxa de codificação
        self.pl = pl  # Payload dos pacotes
        self.simulation_time = simulation_time  # Tempo total da simulação
        self.adr_enabled = adr_enabled  # Controle do Adaptive Data Rate (ADR)
        self.num_devices = num_devices  # Número total de dispositivos
        self.num_gateways = num_gateways  # Número total de gateways
        self.area_size = area_size  # Área da rede (km²)
        self.lambda_rate = lambda_rate  # Taxa de movimento dos dispositivos
        self.speed = speed  # Velocidade dos dispositivos
        self.sf_range = sf_range  # Spreading Factors disponíveis
        self.tx_power = tx_power  # Potência de transmissão
        self.device_data = []
        self.devices = []  # Lista para armazenar dispositivos
        self.gateways = []  # Lista para armazenar gateways
        self.positions = {"devices": {}, "gateways": {}}  # Dicionário de posições
        self.packet_tracker = PacketTracker()  # Rastreamento de pacotes
        self.lorawan_mac = LoRaWANMAC(self)  # Gerenciamento MAC do LoRaWAN
        self.network_throughput = NetworkThroughput(self)
        self.throughput_calculator = NetworkThroughput(self)
        self.current_time = 0
        self.initialize_devices()
        self.mobility_enabled = mobility_enabled
        self.model_pathloss = model_pathloss

        self.initialize_gateways()
        for device in self.devices:
            device.update_coverage_status()

    def calculate_noise_floor(self, bw):
        """
        Calcula o valor do ruído de fundo (noise floor) em dBm com base na largura de banda (BW) do dispositivo.
        :param bw: Largura de banda (em Hz)
        :return: O valor do noise floor em dBm.
        """
        noise_floor = 10 * np.log10(k * temperatura * bw) - noise_figure
        return noise_floor

    def initialize_devices(self):
        """Inicializa os dispositivos finais em grade (matrix)."""
        rows = int(np.ceil(np.sqrt(self.num_devices)))
        cols = int(np.ceil(self.num_devices / rows))
        x_grid = np.linspace(0, self.area_size, cols, endpoint=False) + (self.area_size / (2 * cols))
        y_grid = np.linspace(0, self.area_size, rows, endpoint=False) + (self.area_size / (2 * rows))

        for i in range(self.num_devices):
            r = i // cols
            c = i % cols
            x, y = x_grid[c], y_grid[r]
            device = EndDevice(
                device_id=i,
                x=x, y=y,
                lambda_rate=self.lambda_rate,
                speed=self.speed,
                sf_range=self.sf_range,
                tx_power=self.tx_power,
                bw=self.bw,
                cr=self.cr,
                pl=self.pl,
                frequency_mhz=self.frequency_mhz,
                network=self
            )
            device.adr_enabled = self.adr_enabled
            self.devices.append(device)
            self.positions["devices"][i] = (x, y)


    def initialize_gateways(self):
        """Inicializa os gateways em grade (matrix)."""
        rows = int(np.ceil(np.sqrt(self.num_gateways)))
        cols = int(np.ceil(self.num_gateways / rows))
        x_grid = np.linspace(0, self.area_size, cols, endpoint=False) + (self.area_size / (2 * cols))
        y_grid = np.linspace(0, self.area_size, rows, endpoint=False) + (self.area_size / (2 * rows))

        for i in range(self.num_gateways):
            r = i // cols
            c = i % cols
            x, y = x_grid[c], y_grid[r]
            gateway = Gateway(
                gw_id=i,
                x=x, y=y,
                network=self
            )
            self.gateways.append(gateway)
            self.positions["gateways"][i] = (x, y)


