    def transmit(self, time):
        """Simula a transmissão de um pacote LoRaWAN e verifica colisões antes da retransmissão."""


        if self.device_id not in self.network.lorawan_mac.device_sessions:
            self.network.lorawan_mac.join_request(self)
            return None


        best_gateway, _, best_rssi = self.network.find_best_gateway(self)
        if best_gateway is None:
            return None


        self.current_gateway = best_gateway
        self.rssi = best_rssi

        rectime = self.calculate_airtime()
        self.energy_model.update_energy(
        mode='transmit',
        duration=rectime,
        device=self,
        rd1=rd1,
        rd2=rd2,
        trx1=trx1,
        trx2=trx2,
        receive_delay1=receive_delay1,
        receive_delay2=receive_delay2
    )

        # 📦 Cria um novo pacote
        packet = Packet(self.device_id, self.sf,self.tx_power, self.bw, self.freq, self.rssi, time, rectime)
        self.last_transmissions.append(packet)


        best_gateway.process_uplink(packet)


        self.network.packet_tracker.add_packet(packet)

        if self.network.adr_enabled:
            self.network.lorawan_mac.process_mac_commands(self)  # ✅ Ajuste de SF e potência centralizado


        if packet.collided:
            self.retransmit(time)

        return packet



